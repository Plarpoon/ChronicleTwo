#!/usr/bin/env python3
"""Write splat's symbol list from the retail executable's own symbol table.

    symbols.py            write ps2/config/<region>/main.symbols.txt
    symbols.py --check    fail if the checked-in list is out of date

Retail names are kept, respelled only where the assembler could not take
them: `,`, `<` and `>` become `_`, as does a `.` before a digit. A name the
table holds more than once (MWCC's `@N` constants, file-local statics) takes
a `__<n>` suffix from its second appearance on, in symbol-table order.
"""

import argparse
import os
import re
import struct
import sys
from collections import Counter
from pathlib import Path

REGION = os.environ.get("REGION", "PAL").lower()
ELF_NAMES = {"pal": "SCES_511.90"}
ELF_PATH = Path(f"rom/{REGION}/extracted/iso/{ELF_NAMES[REGION]}")
OUT_PATH = Path(f"ps2/config/{REGION}/main.symbols.txt")

HEADER = ["// Retail's own symbol table.",
          "// Generated by scripts/build/symbols.py; do not edit.", ""]
SKIP_NAMES = {"gcc2_compiled.", "__gnu_compiled_c", "__gnu_compiled_cplusplus",
              "__bss_end", "_end", "end", "_stack"}

SHT_SYMTAB = 2
STT_NOTYPE, STT_OBJECT, STT_FUNC = 0, 1, 2


def read_symbols(path):
    """(symbols in table order, the main image's (start, end))."""
    data = path.read_bytes()
    shoff, = struct.unpack_from("<I", data, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)
    sections = []
    for i in range(shnum):
        fields = struct.unpack_from("<10I", data, shoff + i * shentsize)
        sections.append(dict(zip(("name", "type", "flags", "addr", "offset", "size",
                                  "link", "info", "align", "entsize"), fields)))
    names = sections[shstrndx]["offset"]
    for s in sections:
        s["name"] = data[names + s["name"]:data.index(b"\0", names + s["name"])].decode()
    main = next(s for s in sections if s["name"] == "main")
    heap = next(s for s in sections if s["name"] == "heap")
    symtab = next(s for s in sections if s["type"] == SHT_SYMTAB)
    strtab = sections[symtab["link"]]["offset"]
    syms = []
    for k in range(symtab["size"] // 16):
        name, value, size, info, _other, _shndx = struct.unpack_from(
            "<IIIBBH", data, symtab["offset"] + k * 16)
        text = data[strtab + name:data.index(b"\0", strtab + name)].decode("latin1")
        syms.append(dict(idx=k, name=text, value=value, size=size, type=info & 15))
    return syms, (main["addr"], heap["addr"])


def normalize(name):
    name = name.replace(",", "_").replace("<", "_").replace(">", "_")
    return re.sub(r"\.(?=[0-9])", "_", name)


def spelled(syms):
    """{symbol index: the name the configuration writes for it}."""
    seen, out = Counter(), {}
    for s in syms:
        if not s["name"]:
            continue
        name = normalize(s["name"])
        seen[name.lower()] += 1
        count = seen[name.lower()]
        out[s["idx"]] = name if count == 1 else f"{name}__{count}"
    return out


def listed(sym, lo, hi):
    name = sym["name"]
    if not name or sym["type"] not in (STT_NOTYPE, STT_OBJECT, STT_FUNC):
        return False
    if not lo <= sym["value"] < hi or name in SKIP_NAMES or name.startswith("."):
        return False
    return not re.fullmatch(r"_\w+_size", name)


def attributes(sym):
    if sym["type"] == STT_FUNC:
        return f"type:func size:{sym['size']:#x} allow_duplicated:True"
    if sym["size"]:
        return f"size:{sym['size']:#x} allow_duplicated:True"
    return "allow_duplicated:True"


def symbol_list():
    syms, (lo, hi) = read_symbols(ELF_PATH)
    names = spelled(syms)
    rows = sorted((s["value"], s["type"] != STT_FUNC, names[s["idx"]], attributes(s))
                  for s in syms if listed(s, lo, hi))
    return "\n".join(HEADER + [f"{n} = 0x{a:08x}; // {at}" for a, _t, n, at in rows]) + "\n"


if __name__ == "__main__":
    os.chdir(os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir, os.pardir)))
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in list is out of date")
    args = parser.parse_args()
    if not ELF_PATH.exists():
        sys.exit(f"{ELF_PATH} does not exist; run scripts/build/extract.py first")
    text = symbol_list()
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != text:
            sys.exit(f"{OUT_PATH} is out of date; run scripts/build/symbols.py")
    else:
        OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUT_PATH.write_text(text)
        print(f"Wrote {OUT_PATH} ({text.count(chr(10)) - len(HEADER)} symbols)")
